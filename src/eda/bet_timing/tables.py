"""Bet timing: the report's tables, printed from results.json and results_lines.json to data/studies/bet_timing/
tables.md (every number in docs/studies/bet_timing/README.md is read from these files).
Run: ./python.sh src/eda/bet_timing/tables.py
"""
from __future__ import annotations

import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[3]
if str(ROOT) not in sys.path:
    sys.path.insert(0, str(ROOT))

from src.eda.bet_timing import common as C  # noqa: E402


def ci(d: dict, p: int = 2, scale: float = 1.0) -> str:
    return f"{scale * d['est']:+.{p}f} [{scale * d['lo']:+.{p}f}, {scale * d['hi']:+.{p}f}]"


def verdict(d: dict, pos: str, neg: str) -> str:
    return pos if d["lo"] > 0 else neg if d["hi"] < 0 else "tie"


def slope(r: dict, i: int = 0, p: int = 2) -> str:
    return f"{r['beta'][i]:+.{p}f} [{r['lo'][i]:+.{p}f}, {r['hi'][i]:+.{p}f}]"


def decomposition_table(rows: list[dict], name_of) -> list[str]:
    out = ["| | Matches | Hours before the start (median) | E(t) | E(close) | S(t) | A(t) | **S − A** | Betting early | "
           "Share inherited, A/S | Move toward the model | Realisation at t / at the close |",
           "|---|---:|---:|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        inh = r["inherited_share"]
        out.append(f"| {name_of(r)} | {r['matches']:,} | {r['early_hours_median']:.0f} | {r['E_early']['est']:+.2f} | "
                   f"{r['E_close']['est']:+.2f} | {r['S_softness']['est']:+.2f} | {r['A_model_loss']['est']:+.2f} | "
                   f"**{ci(r['net_E_early_minus_E_close'])}** | "
                   f"{verdict(r['net_E_early_minus_E_close'], 'gains', 'loses')} | "
                   f"{inh['est']:.2f} [{inh['lo']:.2f}, {inh['hi']:.2f}] | {slope(r['move_toward_model'])} | "
                   f"{r['sizing_early']['beta'][1]:.2f} / {r['sizing_close']['beta'][1]:.2f} |")
    return out


def main() -> int:
    res = C.read_json(C.OUT / "results.json")
    lines = C.read_json(C.OUT / "results_lines.json")
    dec = {r["label"] + "|" + r["early"]: r for r in res["decomposition"]}
    md = ["# Bet timing: tables (generated by src/eda/bet_timing/tables.py)", ""]

    md += ["## BetOnline: the opening line against the last line", ""]
    names = [("all", "All"), ("2020-2024", "2020–2024"), ("2025-2026", "2025–2026"), ("men", "Men"),
             ("women", "Women"), ("slams_and_1000s", "Slams, 1000s, Finals"), ("500s_and_250s", "500s and 250s"),
             ("openers", "First match at the event"), ("later_rounds", "Later rounds")]
    names += [(f"season_{s}", str(s)) for s in C.SEASONS]
    names += [(f"open_{a}-{b}h", f"Opened {a}–{b} h before" if b != "inf" else f"Opened over {a} h before")
              for a, b in (("0", "8"), ("8", "16"), ("16", "24"), ("24", "48"), ("48", "inf"))]
    rows = []
    for key, label in names:
        r = dec.get(f"betonline|known|{key}|bol_open")
        if r:
            r = dict(r, _name=label)
            rows.append(r)
    md += decomposition_table(rows, lambda r: r["_name"])
    r = dec["betonline|all_priced|all|bol_open"]
    md += ["", f"Every priced match (inputs not required at the opening): {r['matches']:,} matches, S − A "
               f"{ci(r['net_E_early_minus_E_close'])}."]
    rc = dec["betonline|known|all|bol_open"]["recalibrated_prices"]
    md += [f"With the prices recalibrated (one slope per tour, other blocks): E(open) {ci(rc['E_early'])}, "
           f"E(close) {ci(rc['E_close'])}, S {ci(rc['S_softness'])}, S − A {ci(rc['net_E_early_minus_E_close'])}.",
           f"Against the market-average close, on the same matches, the model's edge is "
           f"{ci(dec['betonline|known|all|bol_open']['E_average_close_td'])}.", ""]

    md += ["## Polymarket: each horizon against the price 30 minutes before the listed start", ""]
    rows = [dict(dec[f"polymarket|known|all|{b}"], _name=f"{C.PM_HORIZONS[b] // 60} h")
            for b in ("pm_h48", "pm_h24", "pm_h12", "pm_h6", "pm_h3", "pm_h1") if f"polymarket|known|all|{b}" in dec]
    md += decomposition_table(rows, lambda r: r["_name"])
    md += ["", "The same matches at every horizon (priced from 24 hours; inputs known at 24 hours):", ""]
    md += decomposition_table([dict(r, _name=f"{r['early_hours_median']:.0f} h") for r in res["polymarket_panel"]],
                              lambda r: r["_name"])
    md += ["", "At 24 hours by group:", ""]
    rows = [dict(dec[f"polymarket|known|{k}|pm_h24"], _name=n) for k, n in
            (("men", "Men"), ("women", "Women"), ("slams_and_1000s", "Slams, 1000s, Finals"),
             ("500s_and_250s", "500s and 250s"), ("openers", "First match at the event"),
             ("later_rounds", "Later rounds")) if f"polymarket|known|{k}|pm_h24" in dec]
    md += decomposition_table(rows, lambda r: r["_name"])
    rc = dec["polymarket|known|all|pm_h24"]["recalibrated_prices"]
    md += ["", f"24 hours with the prices recalibrated: E(24 h) {ci(rc['E_early'])}, E(close) {ci(rc['E_close'])}, "
               f"S − A {ci(rc['net_E_early_minus_E_close'])}.", ""]

    v = res["venues_same_matches"]
    md += ["## The two venues on the same matches (2025–2026)", "",
           f"{v['matches']:,} matches; BetOnline's opening a median {v['bol_open_hours_median']:.0f} hours before the "
           f"listed start.", "",
           "| Comparison | mLL | Reading |", "|---|---|---|",
           f"| BetOnline's last line − Polymarket's 30-minute price (+ = Polymarket sharper) | "
           f"{ci(v['betonline_close_minus_polymarket_close'])} | "
           f"{verdict(v['betonline_close_minus_polymarket_close'], 'Polymarket sharper', 'BetOnline sharper')} |",
           f"| BetOnline's opening − Polymarket's 24-hour price (+ = Polymarket sharper) | "
           f"{ci(v['betonline_open_minus_polymarket_24h'])} | "
           f"{verdict(v['betonline_open_minus_polymarket_24h'], 'Polymarket sharper', 'BetOnline sharper')} |"]
    for b, n in (("bol_open", "BetOnline's opening"), ("bol_close", "BetOnline's last line"),
                 ("pm_h24", "Polymarket 24 hours out"), ("pm_m30", "Polymarket 30 minutes out"),
                 ("td", "the market-average close")):
        md.append(f"| The model's edge over {n} (+ = model better) | {ci(v['E_' + b])} | "
                  f"{verdict(v['E_' + b], 'model better', 'price better')} |")
    md.append("")

    md += ["## Money at BetOnline (completed matches; the owner's staking rule)", "",
           "| Group | Threshold | Bets at the opening / last line | ROI at the opening | ROI at the last line | "
           "Opening − last line, profit per 100 matches | CLV ROI at the opening / last line | Opening − last line, "
           "CLV per 100 matches |", "|---|---|---|---|---|---|---|---|"]
    for m in res["money_betonline"]:
        grp = m["label"].replace("betonline|", "")
        for tau in ("tau_0.0", "tau_0.02", "tau_0.05"):
            t = m[tau]
            o, c = t["open"], t["close"]
            md.append(f"| {grp} | {tau[4:]} | {o['bets']:,} / {c['bets']:,} | {ci(o['roi'], 1, 100)}% | "
                      f"{ci(c['roi'], 1, 100)}% | {ci(t['open_minus_close_profit_per_100'])} | "
                      f"{100 * o['clv_roi']['est']:+.1f}% / {100 * c['clv_roi']['est']:+.1f}% | "
                      f"{ci(t['open_minus_close_clv_per_100'])} |")
    md.append("")

    md += ["## Money at Polymarket ($1 at the ask: mid + half a cent, with the taker fee of the moment)", "",
           "| Horizon | Threshold | Bets early / at the close | ROI early | ROI at the close | Early − close, profit "
           "per 100 matches | CLV ROI early / at the close | Early − close, CLV per 100 matches |",
           "|---|---|---|---|---|---|---|---|"]
    for m in res["money_polymarket"]:
        for tau in ("tau_0.0", "tau_0.02"):
            t = m[tau]
            e, c = t["early"], t["close"]
            md.append(f"| {C.PM_HORIZONS[m['early']] // 60} h | {tau[4:]} | {e['bets']:,} / {c['bets']:,} | "
                      f"{ci(e['roi'], 1, 100)}% | {ci(c['roi'], 1, 100)}% | "
                      f"{ci(t['early_minus_close_profit_per_100'])} | {100 * e['clv_roi']['est']:+.1f}% / "
                      f"{100 * c['clv_roi']['est']:+.1f}% | {ci(t['early_minus_close_clv_per_100'])} |")
    md.append("")

    md += ["## Re-sizing the plug-in out of sample (+ = re-sized better)", "", "| Population | Scheme | At t | At the close |",
           "|---|---|---|---|"]
    for r in res["resized"]:
        blocks = [k for k in r if isinstance(r[k], dict) and "gain_resized_over_plugin" in r[k]]
        early = [k for k in blocks if k not in ("bol_close", "pm_m30")][0]
        close = [k for k in blocks if k in ("bol_close", "pm_m30")][0]
        md.append(f"| {r['label']} ({early}) | {r['scheme']} | {ci(r[early]['gain_resized_over_plugin'])} | "
                  f"{ci(r[close]['gain_resized_over_plugin'])} |")
    md.append("")

    md += ["## Trained on the opening line against the plug-in (BetOnline; + = the second named better)", "",
           "| Period | Tour | First | Second | Matches | mLL | Reading |", "|---|---|---|---|---:|---|---|"]
    for c in lines["comparisons"]:
        md.append(f"| {c['period']} | {c['tour']} | {c['base']} | {c['arm']} | {c['n']:,} | {ci(c)} | "
                  f"{verdict(c, 'second better', 'first better')} |")
    md += ["", "Realisation of each forecast's disagreement with the opening line, 2022–2026 (1 = right-sized):", ""]
    for k, s in lines["sizing_2022_2026"].items():
        md.append(f"* {k}: {s['realisation']:.2f} [{s['lo']:.2f}, {s['hi']:.2f}], price slope {s['price_slope']:.2f}")
    (C.OUT / "tables.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    print(f"wrote {C.OUT / 'tables.md'} ({len(md)} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main())
